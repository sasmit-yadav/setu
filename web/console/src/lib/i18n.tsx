const DICT: Record<Lang, Record<string, string>> = { en: EN, hi: HI, ml: ML, mr: MR };

function interpolate(template: string, vars?: Vars): string {
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (_, key: string) =>
    vars[key] == null ? `{${key}}` : String(vars[key]),
  );
}

type Ctx = {
  lang: Lang;
  setLang: (next: Lang) => void;
  t: (key: string, vars?: Vars) => string;
};

const I18nContext = createContext<Ctx | null>(null);

function readStored(): Lang {
  try {
    const raw = localStorage.getItem(STORAGE);
    if (raw === "ml" || raw === "mr" || raw === "en" || raw === "hi") return raw;
  } catch {
    /* ignore */
  }
  return "en";
}

export function LangProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(readStored);

  const setLang = useCallback((next: Lang) => {
    setLangState(next);
    try {
      localStorage.setItem(STORAGE, next);
    } catch {
      /* ignore */
    }
  }, []);

  useEffect(() => {
    document.documentElement.lang = lang;
  }, [lang]);

  const t = useCallback(
    (key: string, vars?: Vars) => {
      const raw = DICT[lang][key] ?? EN[key] ?? key;
      return interpolate(raw, vars);
    },
    [lang],
  );

  const value = useMemo(() => ({ lang, setLang, t }), [lang, setLang, t]);
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useT(): Ctx {
  const ctx = useContext(I18nContext);
  if (!ctx) throw new Error("LangProvider missing");
  return ctx;
}

export function lookup(t: Ctx["t"], prefix: string, code: string): string {
  const key = `${prefix}.${code}`;
  const got = t(key);
  return got === key ? code.replaceAll("_", " ") : got;
}
